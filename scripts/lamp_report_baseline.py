def q(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def ref(table, key, code, pk):
    return f"(SELECT {pk} FROM {table} WHERE {key}={q(code)} AND deleted_flag=0)"


def product(code):
    return ref("mdm_product", "product_code", "LAMP-" + code, "product_id")


def operation(code):
    return ref("process_operation", "operation_code", "LAMP-OP-" + code, "operation_id")


def route(code):
    return ref("process_route", "route_code", "LAMP-ROUTE-" + code + "-V01", "route_id")


