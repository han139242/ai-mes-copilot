// 默认导出生产制造资源数组，由resources/index.js统一汇总并生成路由菜单。
function onlyRawWarehouse(option) {
  const row = option?.row || {};
  return row.status !== 'ENABLE' || !['RAW', 'SEMI', 'SEMI_FINISHED'].includes(row.warehouseType);
}

// 整机工单只领原材料：半成品由组件工单整份领用、检验合格后自动交接给整机，
// 整机再去半成品仓领一次会重复占用同一份组件，领料单也会挂错工单。
function isRootWorkOrder(row) {
  return Boolean(row) && row.workOrderType === 'ROOT';
}

function issueWarehouseFilter(option, row) {
  if (onlyRawWarehouse(option)) {
    return false;
  }
  return !isRootWorkOrder(row) || (option?.row || {}).warehouseType === 'RAW';
}

// 任务和派工复用工单领料命令，只补 required-issued 的差额，并带回原页面定位。
function supplementMaterialActions(source) {
  const context = (row) => ({
    workOrderId: row.workOrderId,
    outboundType: 'MATERIAL_ISSUE',
    returnResource: source,
    returnFocus: source === 'mfg-task' ? row.taskId : row.dispatchId,
    returnDispatchId: row.dispatchId,
    from: row.taskNo || row.dispatchNo,
  });
  return [
    {
      key: 'supplement-material-issue', label: '补充领料', icon: 'package', method: 'post', type: 'warning',
      path: (row) => `/api/mfg/work-order/${row.workOrderId}/generate-material-issue`,
      visible: (row) => source === 'mfg-task'
        ? row.taskType === 'SUPPLEMENT' && ['WAIT_START', 'RUNNING', 'PAUSED'].includes(row.status)
        : ['RELEASED', 'ACCEPTED', 'RUNNING'].includes(row.status),
      description: '只补领尚未到位的数量。原料仓沿用制造领料；半成品仓整份领用已有组件，先完成领用检验再转线边，余量不足整份时只能改领原材料。已开工组件不能直接替换为库存，整机装配仍须生产。已有待处理领料单时先完成或撤回。',
      fields: [
        field('warehouseId', { label: '领料来源仓', required: true, type: 'reference',
          reference: 'wms-warehouse', optionFilter: issueWarehouseFilter }),
        field('remark', { type: 'textarea' }),
      ],
      successNavigate: { targetResource: 'wms-outbound-order',
        query: (data, row) => ({ ...context(row),
          workOrderId: data?.workOrderId || row.workOrderId, focus: data?.outboundId }) },
    },
    {
      key: 'view-material-issues', label: '领料记录', icon: 'arrow', kind: 'navigate',
      targetResource: 'wms-outbound-order', query: context,
      visible: (row) => Boolean(row.workOrderId),
    },
  ];
}

