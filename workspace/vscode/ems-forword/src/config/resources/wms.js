const confirmAction = (kind, idField, label = '确认') => ({
  key: `confirm-${kind}`,
  label,
  icon: 'check',
  method: 'put',
  type: 'success',
  path: (row) => `/api/wms/${kind}-order/${row[idField]}/confirm`,
  // 生产领料必须走“领料转线边”：它同时扣原料仓、加线边占用并置为已确认。
  // 普通“确认出库”只扣原料仓、不加线边，用在领料单上会把闭环打断，因此不提供该按钮。
  visible: (row) => row.auditStatus === 'SUBMITTED' && !(kind === 'outbound' && row.outboundType === 'MATERIAL_ISSUE'),
  fields: [field('remark', { type: 'textarea' })],
  previewPatch: () => ({ auditStatus: 'APPROVED' }),
});

const withdrawAction = (kind, idField) => ({
  key: `withdraw-${kind}`,
  label: '撤回修改',
  icon: 'refresh',
  method: 'put',
  type: 'warning',
  path: (row) => `/api/wms/${kind}-order/${row[idField]}/withdraw`,
  visible: (row) => row.auditStatus === 'SUBMITTED',
  fields: [field('remark', { label: '撤回原因（选填）', type: 'textarea' })],
  previewPatch: () => ({ auditStatus: 'CLOSED' }),
});

